const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const c = {console, setTimeout, clearTimeout}; c.self = c;
vm.createContext(c);
for(const file of ['vendor/iztro.min.js','forecast.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),c);
const a = c.iztro.astro.bySolar('2000-8-16',2,'女',true,'zh-CN');
const f = c.ZiweiForecast.calculate(a,2027);
assert.equal(f.yearly.heavenlyStem,'丁');
assert.equal(f.yearly.earthlyBranch,'未');
assert.equal(f.age,28);
assert.equal(f.yearly.palaceNames.length,12);
assert.equal(f.yearly.palaceNames[f.yearly.index],'命宫');
assert.equal(f.soulPalace,a.palaces[f.yearly.index].name);
assert.deepEqual(Array.from(f.transformations,t=>t.star),['太阴','天同','天机','巨门']);
assert(f.transformations.every(t=>t.originPalace!=='未定位'&&t.yearlyPalace!=='未定位'));
assert.equal(c.ZiweiForecast.series(a,2027).length,5);
assert.equal(c.ZiweiForecast.series(a,2099).length,2);
assert.notEqual(c.ZiweiForecast.calculate(a,2028).yearly.index,f.yearly.index);
assert.throws(()=>c.ZiweiForecast.calculate(a,1999));
assert.throws(()=>c.ZiweiForecast.calculate(a,2027.5));
assert.throws(()=>c.ZiweiForecast.calculate(a,2101));
const infant = c.ZiweiForecast.calculate(a,2000);
assert.equal(infant.targetDate,'2000-8-16');
assert.equal(infant.age,1);
assert(infant.decadalText.includes('童限'));
const older = c.iztro.astro.bySolar('1900-1-1',0,'男',true,'zh-CN');
assert.equal(c.ZiweiForecast.calculate(older,2100).decadalText,'超出本盘大限范围');
console.log('PASS: 2027 four transformations, palace alignment, age, five-year range, invalid years, childhood and out-of-range decades.');
console.log(JSON.stringify({year: f.year,age:f.age,soulPalace:f.soulPalace,decadal:f.decadalText,transformations:f.transformations},null,2));
